import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { command, readWorkspace } from '../src/lib/service';
import { sql, transaction } from '../src/lib/db';
import { playVideo, downloadFile } from '../src/lib/files';
after(() => sql.end());

test('Monday feedback gates only the configured module, including direct commands/files, and unlocks once', async () => {
  const learner = '10000000-0000-4000-8000-000000000002';
  const admin = '10000000-0000-4000-8000-000000000004';
  const [assignment] = await sql`select * from lms.assignments where module=2 limit 1`;
  const material = randomUUID(), video = randomUUID();
  await sql`update lms.assignments set published=true,opens_at=null where id=${assignment.id}`;
  await sql`insert into lms.materials(id,module,title,published) values(${material},2,'Feedback gate test',true)`;
  await sql`insert into lms.files(id,owner_id,name,mime,size) values(${video},${admin},'gate-test.mp4','video/mp4',10)`;
  await sql`insert into lms.material_files values(${material},${video})`;
  await sql`insert into lms.module_feedback_prompts values(2,now()+interval '1 day') on conflict(module) do update set request_after=excluded.request_after`;
  try {
    const before = await readWorkspace(learner);
    assert.equal(before.feedbackRequests[0].required, false);
    assert.ok(before.materials.some((m: any) => m.id === material));
    const draft = await command(learner, 'draft.create', { assignmentId: assignment.id });
    await sql`update lms.module_feedback_prompts set request_after=now()-interval '1 minute' where module=2`;
    const locked = await readWorkspace(learner);
    assert.equal(locked.feedbackRequests[0].required, true);
    assert.ok(!locked.materials.some((m: any) => m.id === material));
    assert.ok(!locked.assignments.some((a: any) => a.module === 2));
    assert.ok(locked.assignments.some((a: any) => a.module === 1), 'other modules remain available');
    assert.ok(!locked.drafts.some((d: any) => d.id === draft.id));
    await assert.rejects(command(learner, 'draft.create', { assignmentId: assignment.id }), /available/);
    await assert.rejects(command(learner, 'draft.save', { draftId: draft.id, expectedRevision: 0, payload: { parts: {} } }), /available/);
    await assert.rejects(playVideo(learner, video), /available/);
    await assert.rejects(downloadFile(learner, video), /available/);
    const notification = locked.notifications.find((n: any) => n.kind === 'feedback.requested');
    assert.equal(notification.channel, 'in_app');
    assert.equal(notification.status, 'sent', 'in-app notification never enters SMTP queue');
    assert.equal(notification.link_path, '/?module=2');
    await readWorkspace(learner);
    const [count] = await sql`select count(*)::int as n from lms.notifications where dedupe_key=${notification.dedupe_key}`;
    assert.equal(count.n, 1);
    await command(learner, 'feedback.send', { module: null, rating: null, body: 'General course comment.', key: randomUUID() });
    assert.equal((await readWorkspace(learner)).feedbackRequests[0].required, true, 'general feedback cannot unlock a module');
    await assert.rejects(command(learner, 'feedback.send', { module: 2, rating: 5, body: '   ', key: randomUUID() }), /Write your feedback/);
    assert.ok((await readWorkspace(admin)).materials.some((m: any) => m.id === material), 'staff remains unrestricted');
    const key = randomUUID();
    const response = { module: 2, rating: 1, body: 'The pace was too fast. Please show the AI steps again.', key };
    const saved = await command(learner, 'feedback.send', response);
    assert.equal((await command(learner, 'feedback.send', response)).id, saved.id);
    const opened = await readWorkspace(learner);
    assert.equal(opened.feedbackRequests[0].required, false, 'any valid rating is accepted');
    assert.ok(opened.notifications.find((n: any) => n.id === notification.id)?.read_at, 'answered request is marked read');
    assert.ok(opened.materials.some((m: any) => m.id === material));
    assert.ok(opened.drafts.some((d: any) => d.id === draft.id), 'existing drafts are preserved');
    const allowed = await transaction(learner, tx => tx`select lms.can_read_file(${video}) as ok`);
    assert.equal(allowed[0].ok, true);
    await sql`delete from lms.notifications where kind='feedback.requested'`;
    await readWorkspace(learner);
    const [repeat] = await sql`select count(*)::int as n from lms.notifications where kind='feedback.requested' and recipient_id=${learner}`;
    assert.equal(repeat.n, 0, 'already submitted feedback is not requested again');
  } finally {
    await sql`delete from lms.module_feedback_prompts where module=2`;
    await sql`update lms.assignments set published=${assignment.published},opens_at=${assignment.opens_at} where id=${assignment.id}`;
    await sql`delete from lms.material_files where material_id=${material}`;
    await sql`delete from lms.materials where id=${material}`;
    await sql`delete from lms.files where id=${video}`;
    await sql`delete from lms.notifications where kind='feedback.requested'`;
  }
});
