import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { command, readWorkspace } from '../src/lib/service';
import { sql } from '../src/lib/db';
import { randomUUID } from 'node:crypto';

const learner = '10000000-0000-4000-8000-000000000001';
const other = '10000000-0000-4000-8000-000000000002';
const reviewer = '10000000-0000-4000-8000-000000000003';
const admin = '10000000-0000-4000-8000-000000000004';
const assignment = '20000000-0000-4000-8000-000000000001';
const answer = { parts: { analysis: { text: 'Mechanic, experience, math and theme.', files: [], images: [] }, concept: { text: 'A new concept for adult players.', files: [], images: [] } } };
after(() => sql.end());

test('real database: private draft → immutable submission → expert decision → new revision', async () => {
  const draft = await command(learner, 'draft.create', { assignmentId: assignment });
  assert.equal((await readWorkspace(reviewer)).drafts.length, 0);
  assert.equal((await readWorkspace(admin)).drafts.length, 0);
  await assert.rejects(command(other, 'draft.save', { draftId: draft.id, expectedRevision: 0, payload: answer }), /not available/);
  await assert.rejects(command(learner, 'draft.submit', { draftId: draft.id, expectedRevision: 0, key: randomUUID() }), /Complete/);
  const saved = await command(learner, 'draft.save', { draftId: draft.id, expectedRevision: 0, payload: answer });
  await assert.rejects(command(learner, 'draft.save', { draftId: draft.id, expectedRevision: 0, payload: answer }), /changed/);
  const key = randomUUID();
  const submitted = await command(learner, 'draft.submit', { draftId: draft.id, expectedRevision: saved.revision, key });
  assert.deepEqual(await command(learner, 'draft.submit', { draftId: draft.id, expectedRevision: saved.revision, key }), submitted);
  assert.equal((await command(learner, 'draft.submit', { draftId: draft.id, expectedRevision: saved.revision, key: randomUUID() })).id, submitted.id);
  await assert.rejects(command(learner, 'draft.save', { draftId: draft.id, expectedRevision: saved.revision, payload: answer }), /submitted/);
  const read = await readWorkspace(reviewer);
  assert.equal(read.people.find((p: any) => p.id === learner)?.name, 'Alex Morgan');
  assert.equal(read.works.find((w: any) => w.id === submitted.work_id)?.status, 'submitted');
  const earlyRevision = await command(learner, 'draft.create', { assignmentId: assignment });
  assert.notEqual(earlyRevision.id, draft.id, 'revision is allowed before feedback');
  await command(reviewer, 'submission.claim', { submissionId: submitted.id });
  const again = await command(reviewer, 'submission.claim', { submissionId: submitted.id });
  assert.equal(again.status, 'in_review');
  assert.equal((await readWorkspace(learner)).claims.filter((c: any) => c.submission_id === submitted.id).length, 1);
  await assert.rejects(command(admin, 'review.publish', { submissionId: submitted.id, expectedRevision:0, action: 'accepted', body: 'Great', key: randomUUID() }), /responsible expert/);
  await command(reviewer, 'review.publish', { submissionId: submitted.id, expectedRevision:0, action: 'needs_revision', body: 'Explain the hook.', key: randomUUID() });
  const revision = await command(learner, 'draft.create', { assignmentId: assignment });
  assert.notEqual(revision.id, draft.id);
  assert.deepEqual(revision.payload, answer);
  const updated = { parts: { ...answer.parts, concept: { ...answer.parts.concept, text: 'Revised hook.' } } };
  await command(learner, 'draft.save', { draftId: revision.id, expectedRevision: 0, payload: updated });
  assert.equal((await readWorkspace(learner)).submissions[0].payload.parts.concept.text, answer.parts.concept.text);
  const second = await command(learner,'draft.submit',{draftId:revision.id,expectedRevision:1,key:randomUUID()});
  const previousReview = (await readWorkspace(reviewer)).reviews.find((r: any) => r.submission_id === submitted.id);
  await command(reviewer,'review.publish',{submissionId:submitted.id,expectedRevision:1,action:'accepted',body:'Historical correction.',replacesId:previousReview.id,reason:'The original criterion was met.',key:randomUUID()});
  const end = await readWorkspace(learner);
  assert.equal(end.works.find((w: any) => w.id === second.work_id).status,'submitted','review of v1 cannot close v2');
  assert.equal((await readWorkspace(other)).reviews.length,0,'other learner has no reviews');
});
